# services/command_processor.py

import time

from services.object_finder import find_object
from services.navigation import generate_navigation
from services.shared_scene import shared_scene
from services.speech import speak

from utils.command_parser import get_command, get_target_object


def get_latest_scene_description(wait_time=8):
    """
    Get the latest scene description.

    If Florence-2 is still analyzing the first frame, wait briefly
    for the scene analyzer to update shared_scene.
    """

    # Check immediately.
    description = shared_scene.get_description()

    if description and description.strip():
        return description.strip()

    print("\nWaiting for scene analysis...")

    start_time = time.time()

    while time.time() - start_time < wait_time:

        description = shared_scene.get_description()

        if description and description.strip():
            print("Scene description is now available.")
            return description.strip()

        time.sleep(0.2)

    return ""


def describe_current_scene():
    """
    Describe the latest scene using the description already
    generated by Florence-2 and the scene reasoning system.

    Gemini is NOT used here.
    """

    description = get_latest_scene_description()

    if description:
        speak(description)
        return description

    message = (
        "I do not have a scene description yet. "
        "Please wait a moment for the camera to analyze the scene."
    )

    speak(message)
    return message


def process_command(command, objects, scene_description):

    intent = get_command(command)

    print("Detected intent:", intent)

    # ---------------------------------
    # Describe surroundings
    # ---------------------------------
    if intent == "describe":

        # Always get the newest description directly
        # from shared_scene.
        return describe_current_scene()

    # ---------------------------------
    # Navigation
    # ---------------------------------
    if intent == "walk":

        # Use latest available scene description.
        latest_description = shared_scene.get_description()

        if not latest_description:
            latest_description = scene_description

        message = generate_navigation(
            latest_description,
            shared_scene.get_objects()
        )

        speak(message)
        return message

    # ---------------------------------
    # Objects in front
    # ---------------------------------
    if intent == "front":

        # Get latest objects directly from shared scene.
        latest_objects = shared_scene.get_objects()

        center_objects = [
            obj
            for obj in latest_objects
            if obj.get("position") == "Center"
        ]

        if center_objects:

            names = ", ".join(
                obj.get("name", "unknown")
                for obj in center_objects
            )

            message = f"Objects in front of you: {names}."

        else:

            message = (
                "I do not currently detect any objects "
                "in the center."
            )

        speak(message)
        return message

    # ---------------------------------
    # Find an object
    # ---------------------------------
    if intent == "find":

        target = get_target_object(command)

        if not target:

            message = (
                "Which object would you like me to find?"
            )

        else:

            latest_objects = shared_scene.get_objects()

            message = find_object(
                target,
                latest_objects
            )

        speak(message)
        return message

    # ---------------------------------
    # Exit
    # ---------------------------------
    if intent == "exit":

        speak(
            "Goodbye. Closing the voice assistant."
        )

        return "EXIT"

    # ---------------------------------
    # Unknown command
    # ---------------------------------
    message = (
        "Sorry, I did not understand. "
        "You can say describe, shelf, outlet, person, "
        "find an object, or guide me."
    )

    speak(message)

    return message